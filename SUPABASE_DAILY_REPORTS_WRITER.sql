-- 작업일보 작성자 기록용 컬럼 (2026-08-09)
--
-- 왜 필요한가: daily_reports에 작성자를 남기는 자리가 없어서, PDF가 "지금 로그인한 사람"을
-- 작성자로 찍고 있었다. 관리자나 다른 팀장이 남의 팀 일보를 열면 작성자가 자기 이름으로
-- 바뀌어 인쇄되는 문제가 있었다.
--
-- 값은 "제출한 사람" 기준으로 기록된다. 행을 처음 만든 사람이 아닌 이유는, 출퇴근체크
-- (checkin) 앱이 출근체크만으로도 그날 행을 먼저 만들 수 있어서 행 생성자가 작성자와
-- 다를 수 있기 때문이다.
--
-- 이 SQL을 실행하지 않아도 앱은 정상 동작한다(컬럼이 없으면 그 값만 빼고 저장하도록
-- 되어 있음). 다만 실행 전까지는 PDF 작성자란이 계속 "-"로 나온다.
--
-- Supabase 대시보드 > SQL Editor에서 실행:

ALTER TABLE daily_reports ADD COLUMN IF NOT EXISTS writer_name text;
ALTER TABLE daily_reports ADD COLUMN IF NOT EXISTS writer_id   text;

-- 참고: 이미 제출된 예전 일보들은 작성자를 알 수 없어 비워둔다(PDF에 "-"로 표시).
-- 모르는 값을 그럴듯한 이름으로 채우면 문서가 틀리게 되므로 일부러 채우지 않는다.
